"""Summarize all runs of one experiment from their manifest.json / results.json."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def find_experiment_dir(output_root: Path, name_or_id: str) -> Path:
    """Find ``<output_root>/<experiment>/`` from a full name (``E001_pi-estimate``) or the
    number alone (``E001``)."""
    exact = output_root / name_or_id
    if exact.is_dir():
        return exact
    matches = sorted(p for p in output_root.glob(f"{name_or_id}_*") if p.is_dir())
    if len(matches) == 1:
        return matches[0]
    if not matches:
        raise FileNotFoundError(f"no runs of {name_or_id!r} under {output_root}")
    names = ", ".join(p.name for p in matches)
    raise ValueError(f"{name_or_id!r} matches several experiments: {names}")


def collect_runs(exp_dir: Path) -> list[dict[str, Any]]:
    runs = []
    for manifest_path in sorted(exp_dir.glob("*/manifest.json")):
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        results_path = manifest_path.parent / "results.json"
        manifest["results"] = (
            json.loads(results_path.read_text(encoding="utf-8")) if results_path.is_file() else {}
        )
        runs.append(manifest)
    return runs


def _fmt(value: Any) -> str:
    if value is None:
        return "-"
    if isinstance(value, float):
        return f"{value:.4g}"
    return str(value)


def render_markdown(experiment: str, runs: list[dict[str, Any]]) -> str:
    """One row per run; result columns are the scalar keys of results.json."""
    result_keys = sorted(
        {
            key
            for run in runs
            for key, value in run["results"].items()
            if isinstance(value, (int, float, str, bool))
        }
    )
    header = ["run_id", "status", "seed", "commit", "duration_s", *result_keys]
    lines = [
        f"# {experiment} runs",
        "",
        f"Generated by `expkit report {experiment}`; `*` after a commit means uncommitted changes.",
        "",
        "| " + " | ".join(header) + " |",
        "|" + "---|" * len(header),
    ]
    for run in runs:
        git = run.get("git") or {}
        commit = (git.get("commit") or "-")[:7] + ("*" if git.get("dirty") else "")
        row = [run["run_id"], run["status"], run["seed"], commit, run.get("duration_s")]
        row += [run["results"].get(key) for key in result_keys]
        lines.append("| " + " | ".join(_fmt(cell) for cell in row) + " |")
    return "\n".join(lines) + "\n"
